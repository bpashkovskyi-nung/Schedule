(function () {
    const availableTabs = new Set([
        'rooms',
        'auditorium-load',
        'teachers',
        'groups',
        'teaching-load',
    ]);
    const activeTabKey = 'schedule.active-tab';
    const formStatePrefix = 'schedule.form.';

    function getSessionValue(key) {
        try {
            return window.sessionStorage.getItem(key);
        } catch {
            return null;
        }
    }

    function setSessionValue(key, value) {
        try {
            window.sessionStorage.setItem(key, value);
        } catch {
            // Session storage can be disabled by the browser or privacy settings.
        }
    }

    function initPeriodFields(formId, periodId, fromId, toId) {
        const form = document.getElementById(formId);
        if (!form) return;

        const period = document.getElementById(periodId);
        const from = document.getElementById(fromId);
        const to = document.getElementById(toId);
        if (!period || !from || !to) return;

        const options = Array.from(period.options);
        function syncDates() {
            const selected = options.find(o => o.value === period.value);
            if (!selected) return;
            if (period.value !== 'custom') {
                from.value = selected.dataset.from || '';
                to.value = selected.dataset.to || '';
            }
            const custom = period.value === 'custom';
            from.disabled = !custom;
            to.disabled = !custom;
        }

        period.addEventListener('change', syncDates);
        syncDates();

        form.addEventListener('submit', function () {
            from.disabled = false;
            to.disabled = false;
        });
    }

    function initCascade(blockId, roomId, roomsJsonId) {
        const block = document.getElementById(blockId);
        const room = document.getElementById(roomId);
        const dataEl = document.getElementById(roomsJsonId);
        if (!block || !room || !dataEl) return;

        const roomsByBlock = JSON.parse(dataEl.textContent || '{}');
        function updateRooms() {
            const blockName = block.value;
            const selected = room.value;
            room.innerHTML = '<option value="">Оберіть аудиторію</option>';
            room.disabled = !blockName;
            if (!blockName) return;

            (roomsByBlock[blockName] || []).forEach(function (r) {
                const opt = document.createElement('option');
                opt.value = r.id;
                opt.textContent = r.name;
                if (r.id === selected) opt.selected = true;
                room.appendChild(opt);
            });
        }

        block.addEventListener('change', updateRooms);
        updateRooms();
    }

    function initDepartmentCascade(deptId, entityId, entitiesJsonId, placeholder) {
        const dept = document.getElementById(deptId);
        const entity = document.getElementById(entityId);
        const dataEl = document.getElementById(entitiesJsonId);
        if (!dept || !entity || !dataEl) return;

        const byDept = JSON.parse(dataEl.textContent || '{}');
        function update() {
            const name = dept.value;
            const selected = entity.value;
            entity.innerHTML = `<option value="">${placeholder}</option>`;
            entity.disabled = !name;
            if (!name) return;
            (byDept[name] || []).forEach(function (e) {
                const opt = document.createElement('option');
                opt.value = e.id;
                opt.textContent = e.name;
                if (e.id === selected) opt.selected = true;
                entity.appendChild(opt);
            });
        }

        dept.addEventListener('change', update);
        update();
    }

    function getFormControls(form) {
        return Array.from(form.elements).filter(control =>
            control.name &&
            control.type !== 'submit' &&
            control.type !== 'button' &&
            control.type !== 'reset' &&
            control.type !== 'file');
    }

    function getControl(form, name) {
        return getFormControls(form).find(control => control.name === name);
    }

    function readFormState(form) {
        const values = {};
        getFormControls(form).forEach(function (control) {
            if (control.type === 'radio' && !control.checked) return;
            if (control.type === 'checkbox') {
                values[control.name] = control.checked;
                return;
            }

            values[control.name] = control.value;
        });

        // Preset periods have dates generated by the server. Store only the period,
        // otherwise yesterday's generated dates would be restored on the next visit.
        if (values.PeriodKey && values.PeriodKey !== 'custom') {
            delete values.FromDate;
            delete values.ToDate;
        }

        return values;
    }

    function saveFormState(form) {
        const tab = form.dataset.scheduleForm;
        if (!tab) return;
        setSessionValue(formStatePrefix + tab, JSON.stringify(readFormState(form)));
    }

    function loadFormState(form) {
        const tab = form.dataset.scheduleForm;
        if (!tab) return null;

        const raw = getSessionValue(formStatePrefix + tab);
        if (!raw) return null;
        try {
            return JSON.parse(raw);
        } catch {
            return null;
        }
    }

    function setControlValue(form, name, value) {
        const control = getControl(form, name);
        if (!control || value === undefined) return;

        if (control.type === 'checkbox') {
            control.checked = value === true || value === 'true';
        } else if (control.type !== 'radio' || control.value === value) {
            control.value = value;
        }
    }

    function restoreFormState(form, state) {
        if (!state) return;

        const cascade = {
            rooms: ['BlockName', 'RoomId'],
            teachers: ['DepartmentName', 'TeacherId'],
            groups: ['DepartmentName', 'GroupId'],
        };
        const dependent = cascade[form.dataset.scheduleForm];

        if (dependent) {
            setControlValue(form, dependent[0], state[dependent[0]]);
            const parent = getControl(form, dependent[0]);
            if (parent) parent.dispatchEvent(new Event('change'));
        }

        const period = getControl(form, 'PeriodKey');
        if (period && state.PeriodKey !== undefined) {
            setControlValue(form, 'PeriodKey', state.PeriodKey);
            period.dispatchEvent(new Event('change'));
        }

        Object.keys(state).forEach(function (name) {
            if (dependent && name === dependent[0]) return;
            if (name === 'PeriodKey') return;
            setControlValue(form, name, state[name]);
        });
    }

    function hasFormQuery(form) {
        const params = new URLSearchParams(window.location.search);
        return getFormControls(form).some(control => params.has(control.name));
    }

    function isRootPage() {
        const path = window.location.pathname.toLowerCase().replace(/\/$/, '');
        return path === '' || path === '/home' || path === '/home/index';
    }

    document.addEventListener('DOMContentLoaded', function () {
        const activeTabInput = document.getElementById('activeTab');
        const serverTab = activeTabInput && availableTabs.has(activeTabInput.value)
            ? activeTabInput.value
            : 'teachers';
        const queryTab = new URLSearchParams(window.location.search).get('tab');
        const storedTab = getSessionValue(activeTabKey);
        const requestedTab = availableTabs.has(queryTab) ? queryTab : null;

        if (isRootPage() && !requestedTab && availableTabs.has(storedTab) && storedTab !== serverTab) {
            const url = new URL(window.location.href);
            url.searchParams.set('tab', storedTab);
            window.location.replace(url.toString());
            return;
        }

        const activeTab = requestedTab || (isRootPage() ? storedTab : null) || serverTab;
        if (availableTabs.has(activeTab)) {
            setSessionValue(activeTabKey, activeTab);
        }

        document.querySelectorAll('[data-schedule-tab]').forEach(function (link) {
            link.addEventListener('click', function () {
                const tab = link.dataset.scheduleTab;
                if (availableTabs.has(tab)) setSessionValue(activeTabKey, tab);
            });
        });

        initPeriodFields('roomsForm', 'roomsPeriod', 'roomsFrom', 'roomsTo');
        initPeriodFields('teachersForm', 'teachersPeriod', 'teachersFrom', 'teachersTo');
        initPeriodFields('groupsForm', 'groupsPeriod', 'groupsFrom', 'groupsTo');
        initPeriodFields('teachingLoadForm', 'teachingLoadPeriod', 'teachingLoadFrom', 'teachingLoadTo');
        initPeriodFields('auditoriumsForm', 'auditoriumsPeriod', 'auditoriumsFrom', 'auditoriumsTo');

        initCascade('roomsBlock', 'roomsRoom', 'roomsByBlockJson');
        initDepartmentCascade('teachersDept', 'teachersTeacher', 'teachersByDeptJson', 'Оберіть викладача');
        initDepartmentCascade('groupsDept', 'groupsGroup', 'groupsByDeptJson', 'Оберіть групу');

        document.querySelectorAll('[data-schedule-form]').forEach(function (form) {
            if (hasFormQuery(form)) {
                saveFormState(form);
            } else {
                restoreFormState(form, loadFormState(form));
            }

            form.addEventListener('input', function () { saveFormState(form); });
            form.addEventListener('change', function () { saveFormState(form); });
            form.addEventListener('submit', function () { saveFormState(form); });
        });
    });
})();
